// Import the Render3DBrush overhead canopy/shrub atlas packed by Magna Urbis
// (web/scripts/pack_forest_brushes.mjs). The zlib stream is copied unchanged:
// both projects decode the same RG8 texture-array bytes.
// Usage: node tools/assets/import_forest_brushes.mjs [path/to/forest-brushes.json]
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const magna = resolve(root, '../city_generator');
const source = resolve(process.argv[2] || resolve(magna, 'web/src/render/assets/fantasy/forest-brushes.json'));
const atlas = JSON.parse(await readFile(source, 'utf8'));
const zlib = Buffer.from(atlas.zlib, 'base64'), pixels = inflateSync(zlib);
const layers = atlas.families.length * atlas.variants;
if (pixels.length !== atlas.size * atlas.size * 2 * layers) throw Error(`Unexpected atlas size ${pixels.length}`);
let revision = 'unknown';
try { revision = execFileSync('git', ['-C', dirname(source), 'log', '-1', '--format=%h', '--', source], { encoding: 'utf8' }).trim() || revision; } catch {}
await writeFile(resolve(root, 'web/forest-brushes.bin'), zlib);
const manifest = {
  url: 'forest-brushes.bin', format: 'zlib RG8 texture array: R coverage, G centred luminance',
  size: atlas.size, families: atlas.families, variants: atlas.variants, layers,
  coverage: atlas.coverage.map(v => Math.round(v * 1e4) / 1e4),
  bytes: pixels.length, sha256: createHash('sha256').update(pixels).digest('hex'),
  source: `Magna Urbis web/src/render/assets/fantasy/forest-brushes.json @ ${revision}`,
};
await writeFile(resolve(root, 'web/terrain_forest_brushes.js'),
  `// Generated by tools/assets/import_forest_brushes.mjs from Magna Urbis. GPL-3.0.\nwindow.TerrainForestBrushes=${JSON.stringify(manifest)};\n`);
console.log(`${layers} brushes, ${atlas.size}px, ${zlib.length} compressed bytes, sha256 ${manifest.sha256.slice(0, 12)}`);
